function tileCentre(tile: Point): Point {
  return { x: (tile.x + HALF) * TILE_SIZE, y: (tile.y + HALF) * TILE_SIZE };
}

function entityCentre(entity: { readonly x: number; readonly y: number }): Point {
  return { x: entity.x + TILE_SIZE * HALF, y: entity.y + TILE_SIZE * HALF };
}

function insideRect(rect: Rect, x: number, y: number): boolean {
  return x >= rect.x && y >= rect.y && x < rect.x + rect.w && y < rect.y + rect.h;
}

/** Where a crawler stands in a stall's doorway: centred on its two-tile front. */
function stallStandPosition(door: Point): Point {
  const stallMiddleOffsetTiles = (STALL_WIDTH_TILES - 1) * HALF;
  return { x: (door.x + stallMiddleOffsetTiles) * TILE_SIZE, y: door.y * TILE_SIZE };
}

function goblinSeed(worldSeed: number, copyIndex: number, slot: number): number {
  return (
    (Math.imul(worldSeed, COPY_SEED_MULTIPLIER) ^
      Math.imul(copyIndex + 1, SLOT_SEED_MULTIPLIER) ^
      Math.imul(slot + 1, COPY_SEED_MULTIPLIER)) >>>
    0
  );
}

function archetypeFor(seed: number): GoblinArchetype {
  const pick = Math.floor(
    bathroomSeedFraction(seed, ARCHETYPE_SALT) * BATHROOM_GOBLIN_ARCHETYPES.length,
  );
  return BATHROOM_GOBLIN_ARCHETYPES[pick] ?? BATHROOM_GOBLIN_ARCHETYPES[0];
}

export class CloggedBathroomSystem
  implements GameSystem, PipeBoardSource, PipeBoardExplainerModel, ObjectiveBeaconSource
{
  readonly copies: readonly BathroomCopy[];
  private readonly pipeWallBeacons: readonly TrackerTarget[];
  private readonly questManager = new QuestManager();
  private phase: CloggedBathroomPhase = 'unmet';
  private explainerSeen = false;

  private board: PipeBoard | null = null;
  private generation: PipeBoardGeneration | null = null;
  private boardDifficulty: Difficulty | null = null;
  private boardOpen = false;
  private explainerOpen = false;

  private visit: StallVisit | null = null;
  private readonly muffled = new TimedSpeech();
  private sparkle: { crawler: HumanPlayer | CatPlayer; frames: number } | null = null;

  /** The copy the party was last standing at, or null when it is at none of them. */
  private here: BathroomCopy | null = null;
  /** The copy whose pipe wall was last worked: the one whose goblins clear in view after the fix. */
  private workedCopy: BathroomCopy | null = null;
  private plumberTalks = 0;
  private plumberLastLine: DialogLine | null = null;
  private noCuttingCount = 0;
  private framesAtCopy = 0;
  private conversationHandle: ConversationHandle | null = null;
  private readonly ambience: AmbientSoundSystem | null;
  private readonly worldSeed: number;

  constructor(private readonly deps: CloggedBathroomDeps) {
    this.worldSeed = deps.gameMap.worldSeed;
    this.questManager.register({
      id: CLOGGED_BATHROOM_QUEST_ID,
      name: CLOGGED_BATHROOM_QUEST_NAME,
      type: 'mini',
      rewards: { xp: CLOGGED_BATHROOM_XP_REWARD },
    });
    this.copies = deps.gameMap.bathroomRooms.map((room, index) => this.buildCopy(room, index));
    this.pipeWallBeacons = this.copies.map(({ room }) => ({
      x: room.pipeWallStandTile.x,
      y: room.pipeWallStandTile.y,
      ...PIPE_WALL_BEACON_FOOTPRINT,
    }));
    if (this.copies.length > 0) {
      prewarmGoblinPlumber();
      for (const archetype of BATHROOM_GOBLIN_ARCHETYPES) prewarmGoblinBystander(archetype);
    }
    this.ambience =
      deps.audio === null || this.copies.length === 0
        ? null
        : new AmbientSoundSystem(deps.audio, []);
    const alreadyFixed = deps.startSolved || deps.gameMap.bathroomPlumbingState === 'fixed';
    this.applyPhase(alreadyFixed ? 'thanked' : 'unmet');
  }

  /** Whether this floor has a bathroom at all. */
  get isPresent(): boolean {
    return this.copies.length > 0;
  }

  get questPhase(): CloggedBathroomPhase {
    return this.phase;
  }

  get isSolved(): boolean {
    return this.phase === 'solved' || this.phase === 'thanked';
  }

  get questStatus(): QuestStatus | null {
    return this.questManager.getStatus(CLOGGED_BATHROOM_QUEST_ID);
  }

  /** Every goblin the bathrooms stand up, plumbers included. */
  allGoblins(): BathroomGoblin[] {
    const goblins: BathroomGoblin[] = [];
    for (const copy of this.copies) {
      goblins.push(copy.plumber);
      for (const slot of copy.line) goblins.push(slot.goblin);
    }
    return goblins;
  }

  // ── Building the copies ──────────────────────────────────────────────────

  private buildCopy(room: BathroomRoomData, index: number): BathroomCopy {
    const plumberSeed = goblinSeed(this.worldSeed, index, PLUMBER_SLOT);
    const plumber = new BathroomGoblin(
      room.plumberTile.x,
      room.plumberTile.y,
      TILE_SIZE,
      'plumber',
      plumberSeed,
      archetypeFor(plumberSeed),
    );
    plumber.faceTile(room.pipeWallStandTile);
    this.deps.roster.add(plumber);

    const posts: Array<{ tile: Point; facing: Point }> = [];
    room.queueTiles.forEach((tile, position) => {
      const ahead = position === 0 ? room.plumberTile : room.queueTiles[position - 1];
      posts.push({ tile, facing: ahead });
    });
    for (const knot of room.doorwayKnots) {
      knot.forEach((tile, position) => {
        const ahead = position === 0 ? room.centre : knot[position - 1];
        posts.push({ tile, facing: ahead });
      });
    }

    const line: LineSlot[] = posts.map((post, slotIndex) => {
      const seed = goblinSeed(this.worldSeed, index, slotIndex);
      const goblin = new BathroomGoblin(
        post.tile.x,
        post.tile.y,
        TILE_SIZE,
        'queue',
        seed,
        archetypeFor(seed),
      );
      goblin.faceTile(post.facing);
      this.deps.roster.add(goblin);
      const loiter =
        room.loiterTiles.length === 0
          ? post.tile
          : room.loiterTiles[slotIndex % room.loiterTiles.length];
      const headOfLine = slotIndex < Math.min(STALL_COUNT, room.stallDoorTiles.length);
      return {
        goblin,
        post: post.tile,
        facing: post.facing,
        loiter,
        stall: headOfLine && slotIndex < room.queueTiles.length ? slotIndex : null,
        beat: { kind: 'post' },
        talkCount: 0,
        lastLine: null,
      };
    });

    const stalls: StallState[] = room.stallDoorTiles.map(() => ({
      door: 'shut',
      occupant: 'none',
      closeIn: 0,
    }));
    const reach: Rect = {
      x: room.bounds.x - COPY_REACH_TILES,
      y: room.bounds.y - COPY_REACH_TILES,
      w: room.bounds.w + COPY_REACH_TILES * 2,
      h: room.bounds.h + COPY_REACH_TILES * 2,
    };
    return { index, room, plumber, line, stalls, reach };
  }

  // ── Phase and quest ──────────────────────────────────────────────────────

  /**
   * Puts the whole bathroom into `phase` as a restore sees it: the map's
   * plumbing, every goblin's post and the quest status, all at once and
   * without any of the moment-to-moment choreography.
   */
  private applyPhase(phase: CloggedBathroomPhase): void {
    this.phase = phase;
    const fixed = phase === 'solved' || phase === 'thanked';
    this.deps.gameMap.setBathroomPlumbing(fixed ? 'fixed' : 'broken');
    for (const copy of this.copies) {
      if (fixed) this.settleCleared(copy);
      else this.settleInLine(copy);
    }
    this.syncQuestStatus();
    this.syncMarkers();
    this.refreshAmbience();
  }

  private syncQuestStatus(): void {
    const status: QuestStatus =
      this.phase === 'unmet' ? 'available' : this.phase === 'thanked' ? 'completed' : 'active';
    this.questManager.restoreStatuses([[CLOGGED_BATHROOM_QUEST_ID, status]]);
  }

  private startQuestIfNew(): void {
    if (this.questManager.getStatus(CLOGGED_BATHROOM_QUEST_ID) !== 'available') return;
    this.questManager.startQuest(CLOGGED_BATHROOM_QUEST_ID);
    this.deps.bus.emit('questStarted', { questId: CLOGGED_BATHROOM_QUEST_ID });
  }

  private plumberMarker(): BathroomGoblinMarker {
    if (this.phase === 'unmet') return 'exclamation';
    if (this.phase === 'solved') return 'question';
    return 'none';
  }

  /** Puts the plumber's glyph in step with the phase; the scene calls it on halted frames too. */
  syncMarkers(): void {
    const marker = this.plumberMarker();
    for (const copy of this.copies) copy.plumber.marker = marker;
  }

  /**
   * Fixes the plumbing in every copy at once. The copy whose pipes were just
   * worked clears in view; every other copy is set straight to its end state.
   */
  markSolved(): void {
    if (this.isSolved || !this.isPresent) return;
    this.startQuestIfNew();
    this.phase = 'solved';
    this.deps.gameMap.setBathroomPlumbing('fixed');
    for (const copy of this.copies) {
      if (copy === this.workedCopy) this.startClearing(copy);
      else this.settleCleared(copy);
    }
    this.syncMarkers();
    this.refreshAmbience();
  }

  private completeQuest(party: CrawlerPair): void {
    if (this.phase !== 'solved') return;
    this.startQuestIfNew();
    this.phase = 'thanked';
    this.questManager.completeQuest(CLOGGED_BATHROOM_QUEST_ID);
    this.syncMarkers();
    const xpApplied = awardPartyXp(
      party.human,
      party.cat,
      CLOGGED_BATHROOM_XP_REWARD,
      this.deps.bus,
    );
    this.deps.bus.emit('questCompleted', { questId: CLOGGED_BATHROOM_QUEST_ID });
    this.deps.bus.emit('questRewardShown', {
      questTitle: CLOGGED_BATHROOM_QUEST_NAME,
      sections: partyXpSections(xpApplied),
    });
  }

  // ── Goblin posts ─────────────────────────────────────────────────────────

  private moveGoblin(goblin: BathroomGoblin, move: () => void): void {
    const fromX = goblin.x;
    const fromY = goblin.y;
    move();
    if (goblin.x !== fromX || goblin.y !== fromY) {
      this.deps.roster.grid.move(goblin, fromX, fromY);
    }
  }

  private settleInLine(copy: BathroomCopy): void {
    for (const slot of copy.line) {
      const { goblin } = slot;
      this.moveGoblin(goblin, () => goblin.placeAtTile(slot.post));
      goblin.faceTile(slot.facing);
      goblin.hidden = false;
      goblin.holdsPlace = true;
      slot.beat = { kind: 'post' };
    }
    this.resetStalls(copy);
  }

  private settleCleared(copy: BathroomCopy): void {
    for (const slot of copy.line) {
      const { goblin } = slot;
      this.moveGoblin(goblin, () => goblin.placeAtTile(slot.loiter));
      goblin.faceTile(copy.room.centre);
      goblin.hidden = false;
      goblin.holdsPlace = false;
      slot.beat = { kind: 'post' };
    }
    this.resetStalls(copy);
  }

  private resetStalls(copy: BathroomCopy): void {
    for (const stall of copy.stalls) {
      if (stall.occupant === 'crawler') continue;
      stall.door = 'shut';
      stall.occupant = 'none';
      stall.closeIn = 0;
    }
  }

  private startClearing(copy: BathroomCopy): void {
    copy.line.forEach((slot, position) => {
      slot.goblin.holdsPlace = false;
      slot.beat = { kind: 'waiting', frames: position * CLEAR_STAGGER_FRAMES };
    });
  }

  private routeTo(goblin: BathroomGoblin, goal: Point): void {
    const fromX = Math.round(goblin.x / TILE_SIZE);
    const fromY = Math.round(goblin.y / TILE_SIZE);
    const path = this.deps.gameMap.findPath(fromX, fromY, goal.x, goal.y, GOBLIN_ROUTE_MAX_TILES);
    if (path.length === 0) {
      this.moveGoblin(goblin, () => goblin.placeAtTile(goal));
      return;
    }
    goblin.walkRoute(path);
  }

  private tickSlot(copy: BathroomCopy, slot: LineSlot): void {
    const { goblin } = slot;
    const beat = slot.beat;
    switch (beat.kind) {
      case 'post':
        return;
      case 'waiting': {
        if (beat.frames > 0) {
          beat.frames--;
          return;
        }
        const stallIndex = slot.stall;
        const stall = stallIndex === null ? undefined : copy.stalls[stallIndex];
        if (stallIndex !== null && stall?.occupant === 'none') {
          stall.occupant = 'goblin';
          this.routeTo(goblin, copy.room.stallDoorTiles[stallIndex]);
          slot.beat = { kind: 'toStall' };
          return;
        }
        this.sayRelieved(slot);
        this.routeTo(goblin, slot.loiter);
        slot.beat = { kind: 'toLoiter' };
        return;
      }
      case 'toStall': {
        this.moveGoblin(goblin, () => goblin.stepRoute());
        if (!goblin.hasArrived || slot.stall === null) return;
        const stall = copy.stalls[slot.stall];
        goblin.hidden = true;
        goblin.isMoving = false;
        this.openDoor(stall, STALL_DOOR_ENTER_FRAMES);
        slot.beat = { kind: 'inStall', frames: 0 };
        return;
      }
      case 'inStall': {
        beat.frames++;
        if (beat.frames === GOBLIN_FLUSH_AT_FRAMES) this.cue('flush');
        if (beat.frames < GOBLIN_STALL_FRAMES || slot.stall === null) return;
        const stall = copy.stalls[slot.stall];
        stall.occupant = 'none';
        this.openDoor(stall, STALL_DOOR_LINGER_FRAMES);
        goblin.hidden = false;
        const sigh = pickFreshLine(
          QUEUE_GOBLIN_LINES.stallSighPool,
          goblin.seed,
          slot.talkCount,
          slot.lastLine,
        );
        slot.lastLine = sigh;
        slot.talkCount++;
        goblin.speech.say(sigh.paragraphs[0], { durationFrames: SIGH_BUBBLE_FRAMES });
        this.cue('goblinRelief');
        this.routeTo(goblin, slot.loiter);
        slot.beat = { kind: 'toLoiter' };
        return;
      }
      case 'toLoiter': {
        this.moveGoblin(goblin, () => goblin.stepRoute());
        if (!goblin.hasArrived) return;
        goblin.isMoving = false;
        goblin.faceTile(copy.room.centre);
        slot.beat = { kind: 'post' };
        return;
      }
    }
  }

  private sayRelieved(slot: LineSlot): void {
    const line = pickQueueLine('fixed', slot.goblin.seed, slot.talkCount, slot.lastLine);
    slot.lastLine = line;
    slot.talkCount++;
    slot.goblin.speech.say(line.paragraphs[0], { durationFrames: RELIEVED_BUBBLE_FRAMES });
  }

  // ── Stalls ───────────────────────────────────────────────────────────────

  private openDoor(stall: StallState, closeIn: number): void {
    if (stall.door === 'shut') this.cue('stallDoorOpen');
    stall.door = 'open';
    stall.closeIn = closeIn;
  }

  private tickDoors(copy: BathroomCopy): void {
    for (const stall of copy.stalls) {
      if (stall.closeIn <= 0) continue;
      stall.closeIn--;
      if (stall.closeIn > 0) continue;
      stall.door = 'shut';
      if (stall.occupant !== 'none') this.cue('stallDoorLatch');
    }
  }

  private stallIsFree(copy: BathroomCopy, stall: number): boolean {
    return copy.stalls[stall]?.occupant === 'none';
  }

  /** Whether a crawler is in, or stepping into, a stall: movement and switching are locked. */
  get isStallVisitActive(): boolean {
    return this.visit !== null;
  }

  /** Frames into the visit in progress, or null when nobody is in a stall. */
  get stallVisitFrame(): number | null {
    return this.visit?.frame ?? null;
  }

  /** Whether `crawler` is inside a stall and out of sight. */
  isCrawlerHidden(crawler: HumanPlayer | CatPlayer): boolean {
    return this.visit?.crawler === crawler && this.visit.frame >= STALL_ENTER_FRAMES;
  }

  /** Sends `crawler` into `stall` of `copy`. Refused while broken, while the stall is taken, or mid-visit. */
  startStallVisit(crawler: HumanPlayer | CatPlayer, copy: BathroomCopy, stall: number): boolean {
    if (!this.isSolved || this.visit !== null || !this.stallIsFree(copy, stall)) return false;
    const state = copy.stalls[stall];
    state.occupant = 'crawler';
    this.openDoor(state, 0);
    crawler.concealed = true;
    crawler.isMoving = false;
    this.visit = { crawler, copy, stall, fromX: crawler.x, fromY: crawler.y, frame: 0 };
    return true;
  }

  private tickVisit(): void {
    const visit = this.visit;
    if (visit === null) return;
    visit.frame++;
    const state = visit.copy.stalls[visit.stall];
    const door = visit.copy.room.stallDoorTiles[visit.stall];
    const stand = stallStandPosition(door);
    const slide = Math.min(1, visit.frame / STALL_ENTER_FRAMES);
    visit.crawler.x = visit.fromX + (stand.x - visit.fromX) * slide;
    visit.crawler.y = visit.fromY + (stand.y - visit.fromY) * slide;
    visit.crawler.isMoving = false;
    if (visit.frame === STALL_ENTER_FRAMES) {
      state.door = 'shut';
      state.closeIn = 0;
      this.cue('stallDoorLatch');
      this.muffled.say(MUFFLED_LINE, {
        durationFrames: STALL_FLUSH_AT_FRAMES - STALL_ENTER_FRAMES,
      });
    }
    if (visit.frame === STALL_FLUSH_AT_FRAMES) this.cue('flush');
    if (visit.frame === STALL_VISIT_FRAMES - STALL_EXIT_DOOR_FRAMES) this.openDoor(state, 0);
    if (visit.frame < STALL_VISIT_FRAMES) return;
    this.finishVisit(visit);
  }

  private finishVisit(visit: StallVisit): void {
    this.visit = null;
    const state = visit.copy.stalls[visit.stall];
    state.occupant = 'none';
    this.openDoor(state, STALL_DOOR_LINGER_FRAMES);
    this.muffled.clear();
    const { crawler } = visit;
    crawler.concealed = false;
    crawler.applyStatus(makeRefreshed());
    crawler.queueFloatingText(REFRESHED_LABEL, 'buff');
    this.deps.announce(refreshedNotice(), REFRESHED_TOAST);
    this.cue('refreshed');
    this.sparkle = { crawler, frames: SPARKLE_FRAMES };
  }

  /** Drops a visit outright, for a rewind: nobody is left behind a door or invisible. */
  private abandonVisit(): void {
    const visit = this.visit;
    if (visit === null) return;
    this.visit = null;
    visit.crawler.concealed = false;
    this.muffled.clear();
  }

  // ── Talking and working ──────────────────────────────────────────────────

  private copyAt(x: number, y: number): BathroomCopy | null {
    const tileX = Math.floor(x / TILE_SIZE);
    const tileY = Math.floor(y / TILE_SIZE);
    return this.copies.find((copy) => insideRect(copy.reach, tileX, tileY)) ?? null;
  }

  /**
   * The plumber outranks everything near him only while he has something to
   * say (a marker over his head); otherwise the nearest target wins. Even
   * marked, a crawler standing plainly at a stall's front, nearer it than him
   * by {@link STALL_OVER_MARKED_PLUMBER_MARGIN_TILES}, is reaching for the
   * stall: he stands in the aisle a tile from the doors, and a quest tier with
   * no such exception would leave the stalls beside him unusable.
   */
  private plumberTalkTier(copy: BathroomCopy, centre: Point, plumberAt: Point): TalkTier {
    if (this.plumberMarker() === 'none') return TALK_TIER_NAMED;
    const plumberDistance = Math.hypot(plumberAt.x - centre.x, plumberAt.y - centre.y);
    const marginPx = STALL_OVER_MARKED_PLUMBER_MARGIN_TILES * TILE_SIZE;
    const atAStall = copy.room.stallDoorTiles.some((door) => {
      const front = entityCentre(stallStandPosition(door));
      return Math.hypot(front.x - centre.x, front.y - centre.y) + marginPx < plumberDistance;
    });
    return atAStall ? TALK_TIER_NAMED : TALK_TIER_QUEST;
  }

  private targetFor(active: { readonly x: number; readonly y: number }): BathroomTarget | null {
    if (this.visit !== null) return null;
    const centre = entityCentre(active);
    const copy = this.copyAt(centre.x, centre.y);
    if (copy === null) return null;
    const candidates: Array<{ target: BathroomTarget; at: Point; tier: TalkTier }> = [];
    const plumberAt = entityCentre(copy.plumber);
    candidates.push({
      target: { kind: 'plumber', copy },
      at: plumberAt,
      tier: this.plumberTalkTier(copy, centre, plumberAt),
    });
    if (!this.isSolved) {
      candidates.push({
        target: { kind: 'pipeWall', copy },
        at: tileCentre(copy.room.pipeWallStandTile),
        tier: TALK_TIER_NAMED,
      });
    }
    copy.room.stallDoorTiles.forEach((door, stall) => {
      if (this.isSolved && !this.stallIsFree(copy, stall)) return;
      const stand = stallStandPosition(door);
      candidates.push({
        target: { kind: 'stall', copy, stall },
        at: entityCentre(stand),
        tier: TALK_TIER_NAMED,
      });
    });
    for (const slot of copy.line) {
      if (slot.goblin.hidden) continue;
      candidates.push({
        target: { kind: 'goblin', copy, slot },
        at: entityCentre(slot.goblin),
        tier: TALK_TIER_AMBIENT,
      });
    }
    const best = pickByTalkPriority(
      candidates,
      (candidate) => candidate.tier,
      (candidate) => Math.hypot(candidate.at.x - centre.x, candidate.at.y - centre.y),
      BATHROOM_TALK_RANGE_PX,
    );
    return best?.target ?? null;
  }

  /** Whether a press from `active` would reach something in a bathroom. */
  wouldInteract(active: { readonly x: number; readonly y: number }): boolean {
    return this.targetFor(active) !== null;
  }

  /** The bathroom's link in the interact chain. Returns whether it took the press. */
  tryInteract(active: HumanPlayer | CatPlayer, party: CrawlerPair): boolean {
    const target = this.targetFor(active);
    if (target === null) return false;
    switch (target.kind) {
      case 'plumber':
        this.talkToPlumber(target.copy, active, party);
        return true;
      case 'pipeWall':
        this.usePipeWall(target.copy);
        return true;
      case 'stall':
        if (this.isSolved) {
          this.startStallVisit(active, target.copy, target.stall);
        } else {
          this.barkNoCutting(target.copy);
        }
        return true;
      case 'goblin':
        this.talkToGoblin(target.slot);
        return true;
    }
  }

  private barkNoCutting(copy: BathroomCopy): void {
    const visible = copy.line.filter((slot) => !slot.goblin.hidden);
    if (visible.length === 0) return;
    const pick = Math.floor(
      bathroomSeedFraction(this.noCuttingCount, BARK_PICK_SALT) * visible.length,
    );
    this.noCuttingCount++;
    const speaker = visible[pick] ?? visible[0];
    speaker.goblin.speech.say(QUEUE_GOBLIN_LINES.noCutting.paragraphs[0], {
      durationFrames: NO_CUTTING_BUBBLE_FRAMES,
    });
    this.cue('goblinGrumble');
  }

  private plumberRequest(lines: NonEmpty<DialogLine>, onClosed: () => void): ConversationRequest {
    return {
      lines,
      reward: null,
      questRelated: true,
      ending: { kind: 'close', onClosed },
      dismiss: { kind: 'allowed', onDismissed: () => undefined },
      haltsWorld: true,
      anchor: null,
      locksKeyboard: true,
    };
  }

  private talkToPlumber(
    copy: BathroomCopy,
    active: HumanPlayer | CatPlayer,
    party: CrawlerPair,
  ): void {
    copy.plumber.faceTile({
      x: Math.round(active.x / TILE_SIZE),
      y: Math.round(active.y / TILE_SIZE),
    });
    switch (this.phase) {
      case 'unmet':
        this.conversationHandle = this.deps.conversation.open(
          this.plumberRequest(PLUMBER_LINES.firstTalk, () => {
            if (this.phase !== 'unmet') return;
            this.phase = 'met';
            this.startQuestIfNew();
            this.syncMarkers();
          }),
        );
        return;
      case 'met':
        this.conversationHandle = this.deps.conversation.open(
          this.plumberRequest(
            [this.nextPlumberLine(PLUMBER_LINES.repeatPool, copy)],
            () => undefined,
          ),
        );
        return;
      case 'solved':
        this.conversationHandle = this.deps.conversation.open(
          this.plumberRequest(PLUMBER_LINES.thanks, () => this.completeQuest(party)),
        );
        return;
      case 'thanked':
        this.conversationHandle = this.deps.conversation.open(
          this.plumberRequest(
            [this.nextPlumberLine(PLUMBER_LINES.afterPool, copy)],
            () => undefined,
          ),
        );
        return;
    }
  }

  private nextPlumberLine(pool: NonEmpty<DialogLine>, copy: BathroomCopy): DialogLine {
    const line = pickFreshLine(pool, copy.plumber.seed, this.plumberTalks, this.plumberLastLine);
    this.plumberLastLine = line;
    this.plumberTalks++;
    return line;
  }

  private talkToGoblin(slot: LineSlot): void {
    const plumbing: BathroomPlumbing = this.isSolved ? 'fixed' : 'broken';
    const line = pickQueueLine(plumbing, slot.goblin.seed, slot.talkCount, slot.lastLine);
    slot.lastLine = line;
    slot.talkCount++;
    const goblin = slot.goblin;
    const request: ConversationRequest = {
      lines: [line],
      reward: null,
      questRelated: false,
      ending: { kind: 'close', onClosed: () => undefined },
      dismiss: { kind: 'allowed', onDismissed: () => undefined },
      haltsWorld: false,
      anchor: {
        position: () => ({ x: goblin.x, y: goblin.y }),
        talkRangeTiles: BATHROOM_TALK_RANGE_TILES,
      },
      locksKeyboard: false,
    };
    const owned =
      this.conversationHandle !== null && this.deps.conversation.isActive(this.conversationHandle);
    if (owned && this.conversationHandle !== null) {
      this.conversationHandle.play(request);
      return;
    }
    this.conversationHandle = this.deps.conversation.open(request);
  }

  /** Whether the conversation on screen is one this bathroom opened. */
  get isDialogOpen(): boolean {
    return (
      this.conversationHandle !== null && this.deps.conversation.isActive(this.conversationHandle)
    );
  }

  // ── The pipe board ───────────────────────────────────────────────────────

  /**
   * Works a copy's pipe wall: the explainer the first time on this save, the
   * board after that. The board is generated on first need, never with the
   * floor: its worst case is too slow for a floor load, and the explainer gives
   * it frames to run in.
   */
  usePipeWall(copy: BathroomCopy): void {
    if (this.isSolved) return;
    this.workedCopy = copy;
    this.ensureGeneration();
    if (!this.explainerSeen) {
      this.explainerOpen = true;
      return;
    }
    this.boardOpen = true;
  }

  private ensureGeneration(): void {
    if (this.board !== null || this.generation !== null) return;
    this.boardDifficulty = settings.difficulty;
    this.generation = createPipeBoardGeneration(this.worldSeed, this.boardDifficulty);
  }

  /**
   * Steps the board's generation within a slice of this frame, and deals a new
   * board when the difficulty has changed under an unsolved one. Called every
   * frame, halted or not: the explainer and the generating board both halt the
   * world, and they are exactly when it has to run.
   */
  tickGeneration(): void {
    const difficultyMoved =
      this.boardDifficulty !== null && this.boardDifficulty !== settings.difficulty;
    if (!this.isSolved && difficultyMoved) {
      this.board = null;
      this.generation = null;
      this.boardDifficulty = null;
      if (this.boardOpen || this.explainerOpen) this.ensureGeneration();
    }
    const generation = this.generation;
    if (generation === null) return;
    const startedAt = performance.now();
    let settled = generation.step();
    while (!settled && performance.now() - startedAt < GENERATION_FRAME_BUDGET_MS) {
      settled = generation.step();
    }
    const result = generation.result;
    if (result === null) return;
    this.board = createPipeBoard(result.layout);
    this.generation = null;
  }

  /** Runs the board's generation to completion now, for a headless harness that cannot wait on frames. */
  generateBoardNow(): PipeBoard {
    this.ensureGeneration();
    while (this.board === null && this.generation !== null) this.tickGeneration();
    if (this.board === null) throw new Error('the bathroom board settled without a board');
    return this.board;
  }

  get isPipeBoardOpen(): boolean {
    return this.boardOpen;
  }

  get pipeBoard(): PipeBoard | null {
    return this.board;
  }

  get pipeBoardGenerationProgress(): number {
    if (this.board !== null) return 1;
    const attempts = this.generation?.attempts ?? 0;
    return attempts / (attempts + GENERATION_PROGRESS_HALF_ATTEMPTS);
  }

  get pipeBoardSolved(): boolean {
    return this.isSolved;
  }

  turnPipeTile(cell: number, direction: TurnDirection): boolean {
    if (this.board === null || this.isSolved) return false;
    return turnTile(this.board, cell, direction);
  }

  playPipeBoardCue(cue: BathroomCue): void {
    this.cue(cue);
  }

  onPipeBoardSolved(): void {
    if (this.board === null || !traceFlow(this.board).won) return;
    this.markSolved();
  }

  closePipeBoard(): void {
    this.boardOpen = false;
  }

  openPipeBoardExplainer(): void {
    this.explainerOpen = true;
  }

  restartPipeBoard(): void {
    if (this.board !== null && !this.isSolved) resetToScramble(this.board);
  }

  get isPipeBoardExplainerOpen(): boolean {
    return this.explainerOpen;
  }

  finishPipeBoardExplainer(): void {
    this.explainerOpen = false;
    this.explainerSeen = true;
    if (!this.isSolved) this.boardOpen = true;
  }

  dismissPipeBoardExplainer(): void {
    this.explainerOpen = false;
    this.explainerSeen = true;
  }

  /** Whether the explainer has been seen on this save. */
  get hasSeenExplainer(): boolean {
    return this.explainerSeen;
  }

  /** The board, its restart confirm and the explainer, for the scene to mount once. */
  surfaces(): readonly Surface[] {
    return [...pipeBoardSurfaces(this), pipeBoardExplainerSurface(this)];
  }

  // ── Frame ────────────────────────────────────────────────────────────────

  update(ctx: SystemContext): void {
    if (!this.isPresent) return;
    const centre = entityCentre(ctx.active);
    this.here = this.copyAt(centre.x, centre.y);
    this.tickVisit();
    this.muffled.tick();
    if (this.sparkle !== null) {
      this.sparkle.frames--;
      if (this.sparkle.frames <= 0) this.sparkle = null;
    }
    for (const copy of this.copies) {
      for (const slot of copy.line) {
        this.tickSlot(copy, slot);
        this.drainOw(slot.goblin);
      }
      this.drainOw(copy.plumber);
      this.tickDoors(copy);
    }
    this.tickIdleCues();
    this.ambience?.updateListener(ctx.active.x, ctx.active.y);
    this.syncMarkers();
  }

  private drainOw(goblin: BathroomGoblin): void {
    if (!goblin.owCuePending) return;
    goblin.owCuePending = false;
    this.cue('goblinOw');
  }

  private tickIdleCues(): void {
    if (this.here === null || this.isSolved) {
      this.framesAtCopy = 0;
      return;
    }
    this.framesAtCopy++;
    if (this.framesAtCopy % PLUMBER_WRENCH_INTERVAL_FRAMES === 0) this.cue('plumberWrench');
    if (this.framesAtCopy % QUEUE_GRUMBLE_INTERVAL_FRAMES === 0) this.cue('goblinGrumble');
  }

  private cue(cue: BathroomCue): void {
    playBathroomCue(this.deps.audio, cue);
  }

  /** The positional loops: broken pipes and an impatient murmur while broken, a quieter room and running sinks after. */
  private refreshAmbience(): void {
    const ambience = this.ambience;
    if (ambience === null) return;
    const emitters: AmbientEmitter[] = [];
    const add = (cue: BathroomCue, at: Point, radiusTiles: number, maxVolume: number): void => {
      const soundId = bathroomCueSound(cue);
      if (soundId === null) return;
      emitters.push({ soundId, x: at.x, y: at.y, radiusTiles, maxVolume });
    };
    for (const copy of this.copies) {
      const { room } = copy;
      if (this.isSolved) {
        add('queueMurmurLoop', room.centre, MURMUR_FIXED_RADIUS_TILES, MURMUR_FIXED_VOLUME);
        for (const sink of room.sinkTiles) add('sinkRunning', sink, SINK_RADIUS_TILES, SINK_VOLUME);
        continue;
      }
      add('brokenPipesLoop', room.pipeWallTile, BROKEN_PIPES_RADIUS_TILES, BROKEN_PIPES_VOLUME);
      add('queueMurmurLoop', room.centre, MURMUR_RADIUS_TILES, MURMUR_BROKEN_VOLUME);
    }
    ambience.setEmitters(emitters);
  }

  // ── Rendering ────────────────────────────────────────────────────────────

  private copyInView(copy: BathroomCopy, camX: number, camY: number): boolean {
    const { reach } = copy;
    return (
      (reach.x + reach.w) * TILE_SIZE >= camX &&
      reach.x * TILE_SIZE <= camX + viewportWidth() &&
      (reach.y + reach.h) * TILE_SIZE >= camY &&
      reach.y * TILE_SIZE <= camY + viewportHeight()
    );
  }

  private stallLooks(copy: BathroomCopy): Array<Pick<BathroomStallLook, 'door' | 'tag'>> {
    return copy.stalls.map((stall) => ({
      door: stall.door,
      tag: stall.occupant === 'none' ? 'vacant' : 'occupied',
    }));
  }

  /**
   * The ground pass: every copy's stalls, pipe wall and puddles, under every
   * body; and the prompt for whatever a press from `promptFor` would reach.
   * Pass no crawler where a press would not reach the bathroom.
   */
  renderGround(
    ctx: CanvasRenderingContext2D,
    camX: number,
    camY: number,
    promptFor: HumanPlayer | CatPlayer | undefined,
  ): void {
    if (!this.isPresent) return;
    const target = promptFor === undefined ? null : this.targetFor(promptFor);
    const plumbing: BathroomPlumbing = this.isSolved ? 'fixed' : 'broken';
    const timeSeconds = performance.now() / MILLISECONDS_PER_SECOND;
    for (const copy of this.copies) {
      if (!this.copyInView(copy, camX, camY)) continue;
      drawBathroomRoomFixtures(ctx, copy.room, camX, camY, TILE_SIZE, {
        plumbing,
        stalls: this.stallLooks(copy),
        pipeWallHighlighted: target?.kind === 'pipeWall' && target.copy === copy,
        timeSeconds,
      });
    }
    if (target !== null) this.renderPrompt(ctx, camX, camY, target);
  }

  private renderPrompt(
    ctx: CanvasRenderingContext2D,
    camX: number,
    camY: number,
    target: BathroomTarget,
  ): void {
    switch (target.kind) {
      case 'plumber':
      case 'goblin': {
        const goblin = target.kind === 'plumber' ? target.copy.plumber : target.slot.goblin;
        drawInteractionPrompt(ctx, goblin.x - camX, goblin.y - camY, TILE_SIZE, 'Talk');
        return;
      }
      case 'pipeWall': {
        const wall = target.copy.room.pipeWallTile;
        drawInteractionPrompt(
          ctx,
          wall.x * TILE_SIZE - camX,
          wall.y * TILE_SIZE - camY,
          TILE_SIZE,
          BATHROOM_PROMPTS.fixPipes,
        );
        return;
      }
      case 'stall': {
        const door = target.copy.room.stallDoorTiles[target.stall];
        const label = this.isSolved ? BATHROOM_PROMPTS.useStall : BATHROOM_PROMPTS.stallOutOfOrder;
        drawInteractionPrompt(
          ctx,
          door.x * TILE_SIZE - camX,
          (door.y - 1) * TILE_SIZE - camY,
          TILE_SIZE * STALL_WIDTH_TILES,
          label,
        );
        return;
      }
    }
  }

  /**
   * The running water in each fixed sink, sorted with the bodies just after
   * the sink it pours into (it shares the sink tile's foot, and fixtures are
   * queued after decorations).
   */
  sortedFixtures(): TownPropRenderable[] {
    if (!this.isSolved) return [];
    const fixtures: TownPropRenderable[] = [];
    const timeSeconds = performance.now() / MILLISECONDS_PER_SECOND;
    for (const copy of this.copies) {
      for (const spot of bathroomSinkSpots(this.deps.gameMap.structure, copy.room)) {
        fixtures.push({
          x: spot.tile.x * TILE_SIZE,
          y: spot.tile.y * TILE_SIZE,
          render: (ctx, camX, camY, tileSize) =>
            drawBathroomSinkWater(
              ctx,
              spot.tile.x * tileSize - camX,
              spot.tile.y * tileSize - camY,
              tileSize,
              {
                side: spot.side,
                running: true,
                timeSeconds,
              },
            ),
        });
      }
    }
    return fixtures;
  }

  /** Over every body: the muffled bubble over an occupied stall and the sparkle of a crawler stepping out. */
  renderAbove(ctx: CanvasRenderingContext2D, camX: number, camY: number): void {
    const visit = this.visit;
    if (visit !== null) {
      const door = visit.copy.room.stallDoorTiles[visit.stall];
      const stand = stallStandPosition(door);
      drawTimedSpeechBubble(
        ctx,
        this.muffled,
        stand.x + TILE_SIZE * HALF - camX,
        (door.y - STALL_BUBBLE_LIFT_TILES) * TILE_SIZE - camY,
        { border: worldPalette.ink.hint, text: worldPalette.ink.bright },
      );
    }
    const sparkle = this.sparkle;
    if (sparkle === null) return;
    const progress = 1 - sparkle.frames / SPARKLE_FRAMES;
    const centre = entityCentre(sparkle.crawler);
    const radius = SPARKLE_RADIUS_TILES * TILE_SIZE * (HALF + progress * HALF);
    const arm = SPARKLE_ARM_TILES * TILE_SIZE;
    ctx.save();
    ctx.globalAlpha = 1 - progress;
    ctx.strokeStyle = worldPalette.ink.gold;
    ctx.lineWidth = SPARKLE_LINE_WIDTH;
    ctx.beginPath();
    for (let point = 0; point < SPARKLE_POINTS; point++) {
      const angle = (point / SPARKLE_POINTS) * FULL_TURN + sparkle.frames * SPARKLE_SPIN;
      const px = centre.x - camX + Math.cos(angle) * radius;
      const py = centre.y - camY + Math.sin(angle) * radius;
      ctx.moveTo(px - arm, py);
      ctx.lineTo(px + arm, py);
      ctx.moveTo(px, py - arm);
      ctx.lineTo(px, py + arm);
    }
    ctx.stroke();
    ctx.restore();
  }

  // ── Guidance ─────────────────────────────────────────────────────────────

  /** The copy the guidance points at: the one the party is at, else the nearest. */
  private guideCopy(): BathroomCopy | null {
    if (this.here !== null) return this.here;
    if (this.workedCopy !== null) return this.workedCopy;
    return this.copies.length > 0 ? this.copies[0] : null;
  }

  get questMarkers(): Array<{ x: number; y: number; type: QuestMarkerType }> {
    const marker = this.plumberMarker();
    if (marker === 'none') return [];
    const type: QuestMarkerType = marker === 'exclamation' ? 'exclamation' : 'question';
    return this.copies.map((copy) => ({
      x: copy.room.plumberTile.x,
      y: copy.room.plumberTile.y,
      type,
    }));
  }

  trackerEntries(): ReadonlyArray<TrackerEntry> {
    const copy = this.guideCopy();
    if (copy === null) return [];
    const base = { id: CLOGGED_BATHROOM_QUEST_ID, name: CLOGGED_BATHROOM_QUEST_NAME };
    switch (this.phase) {
      case 'unmet':
        return [
          {
            ...base,
            status: 'available',
            objective: FIX_OBJECTIVE,
            hint: 'The plumber at the head of the bathroom line knows what is wrong. Sort of.',
            target: copy.room.plumberTile,
          },
        ];
      case 'met':
        return [
          {
            ...base,
            status: 'active',
            objective: FIX_OBJECTIVE,
            hint: 'The pipes are behind the panel on the bathroom wall.',
            target: copy.room.pipeWallStandTile,
          },
        ];
      case 'solved':
        return [
          {
            ...base,
            status: 'active',
            objective: 'Tell the plumber the pipes are fixed',
            target: copy.room.plumberTile,
          },
        ];
      case 'thanked':
        return [{ ...base, status: 'completed', objective: 'The line is moving again' }];
    }
  }

  /**
   * A beam over every pipe wall from the moment the plumber has asked for the
   * fix until it is done. Independent of the Journal, which floor 2 does not
   * have: without it nothing would say which wall of a crowded room he meant.
   * Stood on the tile the pipes are worked from, so its pool is where to stand,
   * and drawn in front of the wall, since the panel and the wall face above
   * the stand tile would otherwise hide the whole shaft and leave only the pool.
   */
  objectiveBeacons(): readonly TrackerTarget[] {
    return this.phase === 'met' ? this.pipeWallBeacons : NO_BEACONS;
  }

  // ── Save zone ────────────────────────────────────────────────────────────

  /**
   * The track to play right now: the puzzle's own music while the pipe board
   * is on screen, null otherwise so the floor's music plays everywhere else in
   * the room, explainer included.
   */
  get pipeBoardMusic(): SoundId | null {
    return this.boardOpen ? this.pipeBoardMusicTrack : null;
  }

  /** The puzzle's track, whether or not the board is up to hear it. */
  get pipeBoardMusicTrack(): SoundId | null {
    return bathroomCueSound('plumbingMusic');
  }

  /**
   * Where a save taken by `body` would resume, or null when it is not standing
   * in a bathroom whose plumbing is fixed. A fixed bathroom is a save point
   * only, never a safe room: nothing about who may enter it changes.
   *
   * The room proper, not the reach its line spills into, so the doorway knots
   * outside never count as being in it.
   */
  saveTileAt(body: { readonly x: number; readonly y: number }): Point | null {
    if (!this.isSolved) return null;
    for (const { room } of this.copies) {
      const saveTile = roomSaveTile(this.deps.gameMap, room, body);
      if (saveTile !== null) return saveTile;
    }
    return null;
  }

  // ── Checkpoint ───────────────────────────────────────────────────────────

  captureCheckpoint(): CloggedBathroomCheckpoint {
    return { phase: this.phase, explainerSeen: this.explainerSeen };
  }

  /**
   * Puts the bathroom back as captured. The board's turns are dropped on
   * purpose: a rewind deals the opening scramble of the same board again.
   */
  restoreCheckpoint(snapshot: CloggedBathroomCheckpoint): void {
    this.abandonVisit();
    this.sparkle = null;
    this.boardOpen = false;
    this.explainerOpen = false;
    if (this.board !== null) resetToScramble(this.board);
    this.explainerSeen = snapshot.explainerSeen;
    for (const copy of this.copies) {
      for (const stall of copy.stalls) {
        stall.door = 'shut';
        stall.occupant = 'none';
        stall.closeIn = 0;
      }
    }
    this.applyPhase(snapshot.phase);
  }

  dispose(): void {
    this.abandonVisit();
    this.ambience?.dispose();
  }
}
