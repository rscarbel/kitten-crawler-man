/**
 * The Clogged Bathroom on floor 2: every copy of the room, its line of
 * goblins and its plumber, the floor's one pipe board, the stalls, and the
 * mini quest "The Clogged Bathroom".
 *
 * There is one board per floor, shared by every copy: opening any copy's pipe
 * wall shows the same board in the same state, and solving it once fixes the
 * plumbing everywhere at once (`GameMap.setBathroomPlumbing`), which is what
 * drops the runtime block on every copy's queue and doorways. The goblins then
 * clear in the copy the party stands in; every other copy skips straight to
 * its loitering end state.
 *
 * What is saved is small on purpose: where the quest stands and whether the
 * explainer has been seen. The board itself is regenerated byte for byte from
 * the world seed and the difficulty, so the turns a player has made live only
 * while the floor is loaded; a reload or a death rewind deals the opening
 * scramble again.
 */

